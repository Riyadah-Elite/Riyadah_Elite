import {
  TESTING_STATUS,
  TOURNAMENT_STATUS,
  USER_ROLES,
  type UserRole,
} from "../constants/constants.js";

/*
 * These mirror the `User` model in prisma/schema.prisma. They are declared as
 * plain unions rather than imported from the generated Prisma client so that
 * services and controllers stay independent of the database layer - swapping
 * the driver later does not change a single type up here.
 *
 * The generated client is still the single source of truth at runtime; the
 * repository is where the two meet.
 */

export type { UserRole } from "../constants/constants.js";
export type TestingStatus =
  (typeof TESTING_STATUS)[keyof typeof TESTING_STATUS];
export type TournamentStatus =
  (typeof TOURNAMENT_STATUS)[keyof typeof TOURNAMENT_STATUS];

/** Enum values, handy for Joi's `valid()` which needs a spreadable list. */
export { USER_ROLES };
export const TESTING_STATUSES = Object.values(
  TESTING_STATUS,
) as TestingStatus[];
export const TOURNAMENT_STATUSES = Object.values(
  TOURNAMENT_STATUS,
) as TournamentStatus[];

/**
 * A user as the API returns it.
 *
 * `password` is deliberately absent: the Prisma client omits that field for
 * every read (see OMITTED_FIELDS in types/database.types.ts), so no handler can
 * accidentally serialise the hash.
 */
export interface User {
  id: string;
  username: string;
  email: string;
  role: UserRole;
  isDeleted: boolean;
  deletedAt: Date | null;
  tokenVersion: number;
  testingStatus: TestingStatus | null;
  exitReason: string | null;
  tournamentStatus: TournamentStatus | null;
  testingPoints: number | null;
  testingRank: string | null;
  isNotificationAllowed: boolean;
  avatarId: string | null;
  createdAt: Date;
  updatedAt: Date;
}

/** The one shape that carries the hash - only the login path may produce it. */
export interface UserWithPassword extends User {
  password: string;
}

/**
 * Columns written on insert. `password` must already be hashed, `id` is
 * generated by the database (cuid), and the audit/derived columns are left to
 * their schema defaults.
 */
export interface CreateUserInput {
  username: string;
  email: string;
  password: string;
  role: UserRole;
  avatarId?: string | null;
}

/** Columns a user may change after registration. `role` is admin-only. */
export interface UpdateUserInput {
  username?: string;
  role?: UserRole;
  isNotificationAllowed?: boolean;
  avatarId?: string | null;
}

/** Testing / tournament progress, kept separate so it can be validated apart. */
export interface UpdateUserProgressInput {
  testingStatus?: TestingStatus;
  exitReason?: string | null;
  tournamentStatus?: TournamentStatus;
  testingPoints?: number;
  testingRank?: string | null;
}

/**
 * An avatar lives in the File model and the user points at it via `avatarId`.
 * `userId` is filled in by the repository when the avatar is linked.
 */
export interface CreateUserFileInput {
  imageUrl?: string | null;
  description?: string | null;
  fileUrl?: string | null;
  userId?: string | null;
}

export interface CreateBlacklistTokenInput {
  token: string;
  userId: string;
  expiresAt: Date;
}

// ---------------------------------------------------------------------------
// Request-level DTOs (what the controller hands to the service)
// ---------------------------------------------------------------------------

/** multipart/form-data: `avatar` arrives as a file, the rest as fields. */
export interface RegisterUserInput {
  username: string;
  email: string;
  password: string;
  role?: UserRole;
  avatarPath: string;
  avatarMimeType: string;
}

export interface LoginUserInput {
  email: string;
  password: string;
}

export interface LogoutUserInput {
  token: string;
  userId: string;
}

export interface ProfileUserInput {
  userId: string;
  token: string;
}

export interface UpdateProfileUserInput {
  userId: string;
  username?: string;
  isNotificationAllowed?: boolean;
}

// ---------------------------------------------------------------------------
// Response shapes
// ---------------------------------------------------------------------------

/**
 * What is safe to hand to *any* authenticated caller: no email, no testing
 * internals, no password. Used by "get user by id" and by the list endpoint so
 * one user cannot harvest everyone's addresses by paging through ids.
 */
export interface PublicUser {
  id: string;
  username: string;
  role: UserRole;
  avatarUrl: string | null;
  createdAt: Date;
}

/** The signed-in user's own profile - adds the private fields. */
export interface UserProfile extends PublicUser {
  email: string;
  isNotificationAllowed: boolean;
  testingStatus: TestingStatus | null;
  testingPoints: number | null;
  testingRank: string | null;
  tournamentStatus: TournamentStatus | null;
  exitReason: string | null;
  updatedAt: Date;
}

/** Normalised pagination, always derived from validated input. */
export interface UserListQuery {
  page: number;
  limit: number;
  /** Rows to skip - computed, never taken from the client. */
  skip: number;
  take: number;
  search?: string;
  role?: UserRole;
}

export interface PaginationMeta {
  page: number;
  limit: number;
  total: number;
  totalPages: number;
  hasNextPage: boolean;
  hasPreviousPage: boolean;
}

export interface PaginatedUsers {
  users: PublicUser[];
  pagination: PaginationMeta;
}

/** Fields an ADMIN may change on another account. */
export interface UpdateUserDetailsInput {
  userId: string;
  username?: string;
  role?: UserRole;
  isNotificationAllowed?: boolean;
  avatarUrl?: string;
}